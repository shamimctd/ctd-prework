# This program checks if a customer qualifies for a discount.
# It asks for the customer`s name and order amount.

name = input("what is your name? ")
amount = float(input("what is your order amount? "))

if amount >= 500:
   print(name, "qualifies for a discount on an order of $", amount)
else:
   print(name, "does not qualify for a discount on an order of $", amount)


